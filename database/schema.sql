-- Khrufai NEW PostgreSQL baseline for a dedicated development database.
-- Based on the Laravel migrations and model relations. No DROP or data rewrite statements.
-- Safe to re-run for this schema; IF NOT EXISTS does not alter existing columns.

CREATE TABLE IF NOT EXISTS khrufai_schema_migrations (
    version VARCHAR(100) PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM khrufai_schema_migrations WHERE version = '001_initial_schema')
       AND EXISTS (
           SELECT 1 FROM information_schema.tables
            WHERE table_schema = 'public'
              AND table_name = ANY (ARRAY['users','auth_sessions','courses','skills','registrations','classes','class_students','meetings','materials','quizzes','questions','assignments','quiz_scores','assignment_submissions','certificates','attendances','announcements','announcement_reads'])
       ) THEN
        RAISE EXCEPTION 'Khrufai tables already exist without a migration marker; refusing to mix schemas.';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    nama_lengkap VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    tingkat_bahasa VARCHAR(255),
    role VARCHAR(16) NOT NULL DEFAULT 'murid' CHECK (role IN ('admin', 'guru', 'murid')),
    email_verified_at TIMESTAMPTZ,
    password VARCHAR(255) NOT NULL,
    remember_token VARCHAR(100),
    theme_preference VARCHAR(16) DEFAULT 'system',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS users_role_idx ON users(role);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users(LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users(LOWER(email));

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    email VARCHAR(255) PRIMARY KEY,
    token VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    session_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    csrf_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx ON auth_sessions(expires_at);
CREATE INDEX IF NOT EXISTS auth_sessions_user_idx ON auth_sessions(user_id);

CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_bahasa VARCHAR(255) NOT NULL,
    kode VARCHAR(255) NOT NULL UNIQUE,
    deskripsi TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_skill VARCHAR(255) NOT NULL,
    kode VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    no_telp VARCHAR(255),
    kursus_pilihan VARCHAR(8) NOT NULL CHECK (kursus_pilihan IN ('eng', 'kor', 'th')),
    tingkat_bahasa VARCHAR(255),
    bukti_bayar_url VARCHAR(255) NOT NULL,
    bukti_kemampuan_dasar VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
    admin_notes TEXT,
    verified_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS registrations_status_created_idx ON registrations(status, created_at DESC);
CREATE INDEX IF NOT EXISTS registrations_user_idx ON registrations(user_id);

CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_course BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    id_guru BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    nama_kelas VARCHAR(255) NOT NULL,
    periode VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'selesai')),
    jumlah_hari SMALLINT CHECK (jumlah_hari IS NULL OR jumlah_hari BETWEEN 1 AND 100),
    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS classes_active_idx ON classes(status, is_archived, created_at DESC);
CREATE INDEX IF NOT EXISTS classes_course_idx ON classes(id_course);
CREATE INDEX IF NOT EXISTS classes_teacher_idx ON classes(id_guru);

CREATE TABLE IF NOT EXISTS class_students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_class BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    id_student BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_class, id_student)
);
CREATE INDEX IF NOT EXISTS class_students_student_idx ON class_students(id_student);

CREATE TABLE IF NOT EXISTS meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_class BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    urutan_pertemuan INTEGER NOT NULL,
    judul_pertemuan VARCHAR(255) NOT NULL,
    deskripsi TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS meetings_class_order_idx ON meetings(id_class, urutan_pertemuan);

CREATE TABLE IF NOT EXISTS materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meeting BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    judul VARCHAR(255) NOT NULL,
    tipe VARCHAR(8) NOT NULL CHECK (tipe IN ('video', 'pdf', 'doc')),
    file_url VARCHAR(255) NOT NULL,
    deskripsi TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meeting BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    id_skill BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    judul_kuis VARCHAR(255) NOT NULL,
    deskripsi TEXT,
    durasi INTEGER,
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_quiz BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    soal TEXT NOT NULL,
    opsi_a TEXT NOT NULL,
    opsi_b TEXT NOT NULL,
    opsi_c TEXT NOT NULL,
    opsi_d TEXT NOT NULL,
    kunci_jawaban CHAR(1) NOT NULL CHECK (kunci_jawaban IN ('A', 'B', 'C', 'D')),
    poin INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meeting BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    id_skill BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    judul_tugas VARCHAR(255) NOT NULL,
    deskripsi TEXT NOT NULL,
    deadline TIMESTAMPTZ,
    poin_maksimal INTEGER NOT NULL DEFAULT 100,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quiz_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_quiz BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    id_student BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    skor INTEGER,
    total_poin INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_quiz, id_student)
);

CREATE TABLE IF NOT EXISTS assignment_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_assignment BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    id_student BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    file_url VARCHAR(255) NOT NULL,
    catatan_siswa TEXT,
    nilai_guru NUMERIC(5,2),
    feedback TEXT,
    submitted_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_assignment, id_student)
);

CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_student BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    id_class BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    nomor_sertifikat VARCHAR(255) NOT NULL UNIQUE,
    file_pdf_url VARCHAR(255),
    tgl_terbit DATE NOT NULL,
    nilai_reading NUMERIC(5,2),
    nilai_writing NUMERIC(5,2),
    nilai_listening NUMERIC(5,2),
    nilai_speaking NUMERIC(5,2),
    nilai_grammar NUMERIC(5,2),
    rata_rata_total NUMERIC(5,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meeting BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    id_student BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL DEFAULT 'hadir' CHECK (status IN ('hadir', 'izin', 'sakit', 'alfa')),
    keterangan TEXT,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_meeting, id_student)
);

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_meeting BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    id_guru BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    judul_pengumuman VARCHAR(255) NOT NULL,
    isi_pengumuman TEXT NOT NULL,
    is_penting BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS announcement_reads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_announcement BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    id_user BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_announcement, id_user)
);

CREATE INDEX IF NOT EXISTS quiz_scores_student_idx ON quiz_scores(id_student);
CREATE INDEX IF NOT EXISTS assignment_submissions_student_idx ON assignment_submissions(id_student);
CREATE INDEX IF NOT EXISTS attendance_student_idx ON attendances(id_student);
CREATE INDEX IF NOT EXISTS certificates_student_class_idx ON certificates(id_student, id_class);

INSERT INTO khrufai_schema_migrations(version) VALUES ('001_initial_schema') ON CONFLICT (version) DO NOTHING;
